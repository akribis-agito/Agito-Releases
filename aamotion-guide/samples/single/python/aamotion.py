def _library_path():
    names = {"win32": "aamotion.dll", "darwin": "libaamotion.dylib"}
    name = names.get(_sys.platform, "libaamotion.so")
    path = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), name)
    if not _os.path.isfile(path):
        raise FileNotFoundError(f"{path} not found: run  python get_sdk.py  once to download the AAMotionNative "
                                "library and AACommServerNative, or copy them from the SDK beside aamotion.py")
    return path


if _C.sizeof(_C.c_void_p) != 8:
    raise RuntimeError("aamotion is 64-bit only: use a 64-bit Python")
_path = _library_path()
if _sys.platform == "win32":
    _os.add_dll_directory(_os.path.dirname(_path))
lib = _C.CDLL(_path)
_bound = {}
_callbacks = []


def _fn(name, restype, argtypes):
    f = _bound.get(name)
    if f is None:
        try:
            f = getattr(lib, name)
        except AttributeError:
            raise NotImplementedError(f"{name} is not in this aamotion library, which is older than aamotion.py") from None
        f.restype, f.argtypes = restype, argtypes
        _bound[name] = f
    return f


def _s(text):
    return None if text is None else text.encode("utf-8")


def _t(raw):
    return "" if raw is None else raw.decode("utf-8", "replace")


def _keep(callback):
    """ctypes frees a callback Python no longer references. Clearing or replacing a handler does not wait for a
    call already running on another thread, so every callback ever registered is held for the life of the process."""
    _callbacks.append(callback)
    return callback


