// Examples for the "User programs" and "CNC interpolation" chapters.
using System;
using System.Threading;
using AAMotion;

namespace ApiSamples
{
    public static class UserProgram
    {
        public static void Run(MotionController c)
        {
            // --8<-- [start:run]
            AAMotionAPI.ProgRun(c, AxisRef.A, threadNumber: 1, taskNumber: 1);   // AProgRun[1],1
            // ...
            AAMotionAPI.ProgHalt(c, AxisRef.A, 1);       // pause thread 1
            AAMotionAPI.ProgReset(c, AxisRef.A, 1);      // back to the start of its task
            AAMotionAPI.ProgHaltAll(c, AxisRef.A);       // pause every thread
            AAMotionAPI.AutoExec(c, AxisRef.A, true);    // run the program at power-up (save to keep it)
            // --8<-- [end:run]
        }

        public static void Print(MotionController c)
        {
            // --8<-- [start:print]
            Action<UserProgramPrintMessage> onPrint = m =>
                Console.WriteLine($"{m.Timestamp:HH:mm:ss.fff} [T{m.Thread}] {m.DisplayText}");

            AAMotionAPI.SetUserProgramPrintHandler(c, onPrint);   // same as c.UserProgramPrintReceived += onPrint
            // ... the user program's printf lines arrive here ...
            AAMotionAPI.ClearUserProgramPrintHandler(c, onPrint);
            // --8<-- [end:print]
        }

        public static void Exchange(MotionController c)
        {
            // --8<-- [start:exchange]
            // the PC hands a recipe number to the program and waits for its answer
            AAMotionAPI.WriteGenData(c, 1, 7);           // AGenData[1] = recipe 7
            AAMotionAPI.WriteGenData(c, 2, 1);           // AGenData[2] = 1: "start" flag the program polls
            while (AAMotionAPI.ReadGenData(c, 2) != 0)   // the program clears it when done
                Thread.Sleep(50);
            int result = AAMotionAPI.ReadGenData(c, 3);
            // --8<-- [end:exchange]
        }
    }

    public static class Cnc
    {
        public static void Square(MotionController c)
        {
            // --8<-- [start:square]
            IGroupAxis g = c.GetGroup(AxisRef.A);             // CNC group A: X = axis A, Y = axis B
            if (!g.ClearBuffer() ||
                !g.SetStartPositions(0, 0, null) ||
                !g.SetMotionProfile(100, 2000000, 2000000, 0) ||
                !g.LinearAbsoluteXY(100000, 0, 50000, 0) ||
                !g.LinearAbsoluteXY(100000, 100000, 50000, 0) ||
                !g.LinearAbsoluteXY(0, 100000, 50000, 0) ||
                !g.LinearAbsoluteXY(0, 0, 50000, 0))
            {
                Console.WriteLine("CNC download failed. Check the controller error.");
                return;
            }
            if (!g.Begin()) { Console.WriteLine("CNC Begin failed."); return; }

            DateTime deadline = DateTime.UtcNow.AddSeconds(30);
            while (!g.IsCNCCompleted(AxisRef.A))
            {
                if (DateTime.UtcNow >= deadline)
                {
                    g.Stop();
                    Console.WriteLine("CNC wait timed out; group Stop requested, verify actual state");
                    return;
                }
                Thread.Sleep(50);
            }
            Console.WriteLine("CNC motion is inactive. Check controller errors and the final positions.");
            // --8<-- [end:square]
        }

        public static void Arc(MotionController c)
        {
            // --8<-- [start:arc]
            IGroupAxis g = c.GetGroup(AxisRef.A);
            // Assumes X and Y are already at (0, 0).
            if (!g.ClearBuffer() ||
                !g.SetStartPositions(0, 0, null) ||
                !g.LinearAbsoluteXY(50000, 0, 40000, 0) ||
                !g.ArcXY(100000, 50000, 50000, 50000, 0, 40000, 0) ||
                !g.Delay(200))
            {
                Console.WriteLine("CNC download failed. Check the controller error.");
                return;
            }
            if (!g.Begin()) Console.WriteLine("CNC Begin failed.");
            // --8<-- [end:arc]
        }

        public static void PauseResume(MotionController c)
        {
            // --8<-- [start:pause]
            AAMotionAPI.Pause(c);        // decelerate along the path and hold
            AAMotionAPI.Resume(c);       // continue from the same point
            AAMotionAPI.GroupStop(c);    // stop the CNC motion
            AAMotionAPI.ClearBuffer(c);  // drop the remaining segments
            // --8<-- [end:pause]
        }

        public static void FromFile(MotionController c)
        {
            // --8<-- [start:file]
            // a CNC program generated by PCSuite's CNC tool
            AAMotionAPI.RunCNCProgramFromFile(c, @"C:\MyApp\part.cnc");
            // --8<-- [end:file]
        }

        public static void IoOnPath(MotionController c)
        {
            // --8<-- [start:io-on-path]
            IGroupAxis g = c.GetGroup(AxisRef.A);
            g.LinearAbsoluteXY(50000, 0, 40000, 0);
            g.GroupDOutSetBit(AxisRef.A, 1);      // output 1 on when the path reaches here (a 1-based output number)
            g.Delay(100);
            g.GroupDOutClearBit(AxisRef.A, 1);
            g.WriteGenData(5, 1);                 // tell the user program "segment 2 reached"
            g.LinearAbsoluteXY(100000, 0, 40000, 0);
            g.Begin();
            // --8<-- [end:io-on-path]
        }
    }
}

